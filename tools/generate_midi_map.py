"""Generate `music_maker_plugin/midi_map.md` from all MIDI projects in `music_maker_plugin/midi/`.

Reuses the parsing and Markdown formatting engine in `analyze_midi.py` / `engine/midi_io.py`
and prepends a structured Quick Navigation Index (with exact line ranges and instrument
groupings) so AI agents can look up any project, track, or instrument selectively without
overflowing context.

Usage:
    python tools/generate_midi_map.py
    python tools/generate_midi_map.py --midi-dir path/to/midi --output path/to/midi_map.md
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import os
import sys

sys.dont_write_bytecode = True

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLUGIN_DIR = os.path.join(REPO_ROOT, "music_maker_plugin")
TOOLKIT_DIR = os.path.join(PLUGIN_DIR, "skills", "soundfont-music", "scripts", "toolkit")
DEFAULT_MIDI_DIR = os.path.join(PLUGIN_DIR, "midi")
DEFAULT_OUTPUT_PATH = os.path.join(PLUGIN_DIR, "midi_map.md")

if TOOLKIT_DIR not in sys.path:
    sys.path.insert(0, TOOLKIT_DIR)

import analyze_midi  # noqa: E402

CATEGORY_RULES = (
    ("Drums / Percussion", ("drum", "kit", "perc", "kick", "snare", "hat", "cymbal", "tom", "fill", "beat")),
    ("Bass", ("bass", "sub", "808", "reese")),
    ("Guitar / Plucked", ("guitar", "gtr", "acoustic", "electric", "nylon", "harp", "pluck", "strum", "ukulele")),
    ("Strings / Pad", ("string", "violin", "viola", "cello", "contrabass", "pad", "choir", "orch", "ensemble")),
    ("Synth / Lead", ("synth", "lead", "arp", "brass", "horn", "sax", "flute", "woodwind", "melody", "vocal", "vox")),
    ("Piano / Keys", ("piano", "ep", "rhodes", "wurli", "key", "organ", "clav", "harpsi", "celesta", "bell")),
)


def classify_instrument_category(file_name: str, track: dict) -> str:
    """Classify a track into a broad arrangement category for fast lookup.

    Prioritizes explicit file/track names over GM program_name because exported DAW
    MIDI tracks often leave program=0 ('piano') by default.
    """
    if track.get("is_drum_hint"):
        return "Drums / Percussion"

    explicit_name = f"{file_name} {track.get('name', '')}".lower()
    for category, tokens in CATEGORY_RULES:
        if any(tok in explicit_name for tok in tokens):
            return category

    program_name = str(track.get("program_name", "")).lower()
    for category, tokens in CATEGORY_RULES:
        if any(tok in program_name for tok in tokens):
            return category
    return "Other"


def _render_group_body(display_target: str, group: dict) -> list[str]:
    """Render one project/file group using analyze_midi.format_markdown without the top title."""
    full_block = analyze_midi.format_markdown(display_target, [group]).splitlines()
    # Skip the leading `# MIDI Reference Library Analysis (...)` title and blank line.
    if len(full_block) >= 2 and full_block[0].startswith("# "):
        return full_block[2:] if full_block[1] == "" else full_block[1:]
    return full_block


def _build_index_lines(
    display_target: str,
    report: list[dict],
    project_ranges: list[tuple[int, int]],
    file_ranges: dict[tuple[str, str], tuple[int, int]],
) -> list[str]:
    """Build the top-of-file Quick Navigation Index with exact 1-based line ranges."""
    lines = [
        f"# MIDI Map (`{display_target}`)",
        "",
        "> Static reference map generated by `tools/generate_midi_map.py`. "
        "Places each project's `readme.md` first, followed by bar-by-bar notes with "
        "velocity, micro-timing offsets, inline CC64 `ped`, and inline `bend=...` target curves.",
        "",
    ]

    if not report:
        lines.append("_Chưa có project MIDI hoặc file `.mid` / `.midi` nào trong thư mục MIDI._")
        lines.append("")
        return lines

    lines.extend([
        "## 1. Project Index",
        "",
        "| # | Project | Type | Files | BPM / Time | Lines (`midi_map.md`) |",
        "|---|---|---|---|---|---|",
    ])
    for idx, (group, (s_line, e_line)) in enumerate(zip(report, project_ranges), start=1):
        kind = "Folder" if group["is_folder"] else "Single"
        files = group.get("files", [])
        bpms = sorted({str(f.get("bpm", "?")) for f in files})
        times = sorted({str(f.get("time_signature", "?")) for f in files})
        bpm_time = f"{'/'.join(bpms)} BPM ({'/'.join(times)})" if files else "N/A"
        lines.append(
            f"| {idx} | `{group['project']}` | {kind} | {len(files)} | {bpm_time} | `L{s_line}-L{e_line}` |"
        )

    lines.extend([
        "",
        "## 2. Instrument & Track Lookup",
        "",
        "| Category | Project | File | Track | Details | Lines |",
        "|---|---|---|---|---|---|",
    ])

    by_category: dict[str, list[tuple[str, dict, dict, tuple[int, int]]]] = defaultdict(list)
    for group in report:
        proj_name = group["project"]
        for f in group.get("files", []):
            frange = file_ranges.get((proj_name, f["relative_path"]), (1, 1))
            for tr in f.get("tracks", []):
                cat = classify_instrument_category(f["file_name"], tr)
                by_category[cat].append((proj_name, f, tr, frange))

    ordered_cats = [c for c, _ in CATEGORY_RULES] + ["Other"]
    for cat in ordered_cats:
        for proj_name, f, tr, (fs_line, fe_line) in by_category.get(cat, []):
            extras = [f"notes={tr['note_count']}", f"vel={tr['velocity_range'][0]}..{tr['velocity_range'][1]}"]
            if tr.get("pedal_count"):
                extras.append(f"pedal={tr['pedal_count']}")
            if tr.get("bent_note_count"):
                extras.append(f"bent={tr['bent_note_count']}")
            elif tr.get("pitchwheel_count"):
                extras.append(f"bend={tr['pitchwheel_count']}")
            if tr.get("rolled_chords"):
                extras.append(f"rolled={tr['rolled_chords']}")
            lines.append(
                f"| {cat} | `{proj_name}` | `{f['file_name']}` | `{tr['name']}` (`{tr['program_name']}`) "
                f"| {', '.join(extras)} | `L{fs_line}-L{fe_line}` |"
            )

    lines.extend(["", "---", ""])
    return lines


def _locate_file_heading_offsets(group_lines: list[str], files: list[dict]) -> dict[str, int]:
    """Find 0-based line offsets of each `### File: ...` heading inside a rendered project block."""
    offsets: dict[str, int] = {}
    file_rel_paths = [f["relative_path"] for f in files]
    search_from = 0
    for rel_path in file_rel_paths:
        needle = f"(`{rel_path}`)"
        for i in range(search_from, len(group_lines)):
            if group_lines[i].startswith("### File:") and needle in group_lines[i]:
                offsets[rel_path] = i
                search_from = i + 1
                break
    return offsets


def build_midi_map_markdown(midi_dir: str, display_target: str | None = None) -> str:
    """Analyze all MIDI projects under `midi_dir` and return full `midi_map.md` content."""
    if display_target is None:
        try:
            display_target = os.path.relpath(midi_dir, REPO_ROOT).replace("\\", "/")
        except ValueError:
            display_target = midi_dir.replace("\\", "/")

    report = analyze_midi.analyze_directory(midi_dir)
    if not report:
        return "\n".join(_build_index_lines(display_target, [], [], {}))

    group_blocks = [_render_group_body(display_target, group) for group in report]
    file_offsets_per_group = [
        _locate_file_heading_offsets(block, group.get("files", []))
        for group, block in zip(report, group_blocks)
    ]

    # Two-pass calculation so line ranges in the Quick Index match the final file lines exactly.
    placeholder_proj = [(1, 1) for _ in report]
    placeholder_files: dict[tuple[str, str], tuple[int, int]] = {}
    pass1_index = _build_index_lines(display_target, report, placeholder_proj, placeholder_files)

    cursor = len(pass1_index) + 1  # 1-based line number where the first project starts
    project_ranges: list[tuple[int, int]] = []
    file_ranges: dict[tuple[str, str], tuple[int, int]] = {}

    for group, block, f_offsets in zip(report, group_blocks, file_offsets_per_group):
        p_start = cursor
        p_end = cursor + len(block) - 1
        project_ranges.append((p_start, p_end))

        files = group.get("files", [])
        sorted_offsets = sorted(
            ((rel, f_offsets[rel]) for rel in (f["relative_path"] for f in files) if rel in f_offsets),
            key=lambda item: item[1],
        )
        for idx, (rel, off) in enumerate(sorted_offsets):
            f_start = p_start + off
            if idx + 1 < len(sorted_offsets):
                f_end = p_start + sorted_offsets[idx + 1][1] - 1
            else:
                f_end = p_end
            file_ranges[(group["project"], rel)] = (f_start, f_end)

        cursor = p_end + 2  # +1 blank separator line between project blocks

    final_index = _build_index_lines(display_target, report, project_ranges, file_ranges)
    if len(final_index) != len(pass1_index):
        raise RuntimeError("Index line count mismatch while computing line ranges.")

    all_lines = list(final_index)
    for idx, block in enumerate(group_blocks):
        if idx > 0:
            all_lines.append("")
        all_lines.extend(block)

    return "\n".join(all_lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate music_maker_plugin/midi_map.md from MIDI projects.")
    parser.add_argument("--midi-dir", default=DEFAULT_MIDI_DIR, help="Path to MIDI library root folder.")
    parser.add_argument("--output", default=DEFAULT_OUTPUT_PATH, help="Output Markdown path.")
    parser.add_argument("--quiet", action="store_true", help="Suppress stdout summary.")
    args = parser.parse_args(argv)

    midi_dir = os.path.abspath(args.midi_dir)
    output_path = os.path.abspath(args.output)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    content = build_midi_map_markdown(midi_dir)
    with open(output_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)

    if not args.quiet:
        line_count = content.count("\n")
        print(f"[OK] Generated {output_path} ({line_count} lines) from {midi_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
